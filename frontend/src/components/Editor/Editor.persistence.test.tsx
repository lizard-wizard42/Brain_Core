import { useEffect } from 'react';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { Editor as TiptapEditor } from '@tiptap/react';
import type { Page, TiptapDoc } from '../../types';
import { Editor } from './Editor';
import { MemoryRouter } from 'react-router-dom';
import { writePageDrag } from './pageDrag';
import { api } from '../../api/client';
import { textEditorDrafts } from './textEditorDrafts';
const captured = vi.hoisted(() => ({ editor: null as TiptapEditor | null }));
vi.mock('../../api/browserSession', () => ({ activeBrowserUserId: () => 'fictional-account' }));
vi.mock('../../hooks/useSocket', () => ({ useSocket: () => ({ joinPage: vi.fn(), leavePage: vi.fn() }) }));
vi.mock('../Shared/sharedPagesContext', () => ({ useSharedPages: () => ({ getEntry: () => undefined, refresh: vi.fn() }) }));
vi.mock('./allPagesCache', () => ({ getCachedAllPages: () => [], loadAllPagesCached: async () => [] }));
vi.mock('./textEditorDrafts', () => ({ textEditorDrafts: { read: vi.fn(), write: vi.fn(), remove: vi.fn() } }));
vi.mock('../../api/client', () => ({ api: { getPageVersions: vi.fn(), getMe: vi.fn(), getPageGrants: vi.fn(), getSubPages: vi.fn(), savePage: vi.fn(), getPage: vi.fn(), patchPage: vi.fn() }, isRevisionConflict: (e: unknown) => String(e).includes('409') }));
vi.mock('../shared/EmojiPicker', () => ({ EmojiPicker: ({ onSelect }: { onSelect: (value: string) => void }) => <button onClick={() => onSelect('📘')}>Choose demo icon</button> }));
vi.mock('./EditorCover', () => ({ CoverImage: () => null }));
vi.mock('./PageNavigation', () => ({ PageNavigation: () => null }));
vi.mock('./SubPagesKanban', () => ({ SubPagesKanban: () => null }));
vi.mock('./ToolbarControls', () => ({ TableControls: () => null }));
vi.mock('./BottomToolbar', () => ({ BottomToolbar: function Toolbar({ editor, saveStatus, onRetrySave }: { editor: TiptapEditor | null; saveStatus: string; onRetrySave: () => void }) {
  useEffect(() => { captured.editor = editor; }, [editor]);
  return <div><span data-testid="save-status">{saveStatus}</span><button onClick={onRetrySave}>Retry save</button></div>;
} }));
const doc = (text: string): TiptapDoc => ({ type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text }] }] });
const page: Page = { id: 'fictional-page', type: 'note', title: 'Study', content: doc('Saved text'), revision: 3, slug: 'study', sort_order: 0, updated_at: '' };
beforeEach(() => {
  vi.resetAllMocks(); captured.editor = null;
  vi.mocked(textEditorDrafts.read).mockResolvedValue(undefined);
  vi.mocked(textEditorDrafts.write).mockResolvedValue(undefined);
  vi.mocked(textEditorDrafts.remove).mockResolvedValue(undefined);
  vi.mocked(api.getPageVersions).mockResolvedValue({ versions: [] });
  vi.mocked(api.getMe).mockResolvedValue({ id: 'fictional-account', name: 'Demo' } as Awaited<ReturnType<typeof api.getMe>>);
  vi.mocked(api.getPageGrants).mockResolvedValue([]);
  vi.mocked(api.getSubPages).mockResolvedValue([]);
  vi.mocked(api.savePage).mockResolvedValue({ ...page, revision: 4 });
  vi.mocked(api.getPage).mockResolvedValue(page);
});
afterEach(() => { cleanup(); vi.useRealTimers(); });
const ready = async () => { render(<Editor page={page} />); await waitFor(() => expect(captured.editor?.isEditable).toBe(true)); };
describe('Real text editor save and recovery integration', () => {
  it('offers recovery before editing and restores the title and Tiptap content', async () => {
    vi.mocked(textEditorDrafts.read).mockResolvedValue({ content: doc('Recovered writing'), title: 'Recovered title', baseRevision: 3 });
    render(<Editor page={page} />);
    const recover = await screen.findByRole('button', { name: 'Recuperar rascunho' });
    expect(captured.editor?.isEditable).toBe(false); expect(api.savePage).not.toHaveBeenCalled();
    fireEvent.click(recover);
    await waitFor(() => expect(captured.editor?.getText()).toBe('Recovered writing'));
    expect(screen.getByRole('textbox', { name: 'Título da página' })).toHaveValue('Recovered title');
    expect(captured.editor?.isEditable).toBe(true);
    fireEvent.click(screen.getByRole('button', { name: 'Retry save' }));
    await waitFor(() => expect(api.savePage).toHaveBeenCalledWith(page.id, expect.objectContaining({ content: doc('Recovered writing'), title: 'Recovered title' }), expect.anything()));
  });
  it('persists actual editor changes immediately, retries failure and preserves rich blocks', async () => {
    await ready();
    vi.mocked(api.savePage).mockRejectedValueOnce(new Error('offline'));
    act(() => { captured.editor!.commands.setContent({ type: 'doc', content: [{ type: 'codeBlock', attrs: { language: 'javascript' }, content: [{ type: 'text', text: '  const value = 1;\n' }] }] }); });
    await waitFor(() => expect(textEditorDrafts.write).toHaveBeenCalled());
    const content = captured.editor!.getJSON();
    fireEvent.change(screen.getByRole('textbox', { name: 'Título da página' }), { target: { value: 'Edited title' } });
    fireEvent.click(screen.getByRole('button', { name: 'Retry save' }));
    await waitFor(() => expect(screen.getByTestId('save-status')).toHaveTextContent('error'));
    expect(textEditorDrafts.remove).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Retry save' }));
    await waitFor(() => expect(screen.getByTestId('save-status')).toHaveTextContent('saved'));
    expect(api.savePage).toHaveBeenLastCalledWith(page.id, expect.objectContaining({ content, title: 'Edited title' }), expect.anything());
  });
  it('keeps a stale recovered draft from overwriting the server', async () => {
    vi.mocked(textEditorDrafts.read).mockResolvedValue({ content: doc('Older draft'), title: 'Older title', baseRevision: 2 });
    render(<Editor page={page} />);
    fireEvent.click(await screen.findByRole('button', { name: 'Recuperar rascunho' }));
    await waitFor(() => expect(captured.editor?.getText()).toBe('Older draft'));
    fireEvent.click(screen.getByRole('button', { name: 'Retry save' }));
    expect(api.savePage).not.toHaveBeenCalled();
    expect(screen.getByRole('button', { name: 'Baixar rascunho' })).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Recarregar do servidor' }));
    await waitFor(() => expect(captured.editor?.getText()).toBe('Saved text'));
    expect(screen.getByRole('textbox', { name: 'Título da página' })).toHaveValue('Study');
  });
  it('continues saving text after changing the page icon', async () => {
    await ready();
    vi.mocked(api.patchPage).mockResolvedValue({ ...page, icon: '📘', revision: 4 });
    fireEvent.click(screen.getByRole('button', { name: '+ ícone' }));
    fireEvent.click(screen.getByRole('button', { name: 'Choose demo icon' }));
    await waitFor(() => expect(screen.getByRole('button', { name: 'Trocar ícone' })).toBeEnabled());
    act(() => { captured.editor!.commands.setContent(doc('Written after icon update')); });
    fireEvent.click(screen.getByRole('button', { name: 'Retry save' }));
    await waitFor(() => expect(api.savePage).toHaveBeenCalledWith(page.id, expect.objectContaining({ revision: 4 }), expect.anything()));
  });
  it('keeps recovery available if the server cannot load the saved version', async () => {
    vi.mocked(textEditorDrafts.read).mockResolvedValue({ content: doc('Keep this draft'), title: 'Local', baseRevision: 3 });
    vi.mocked(api.getPage).mockRejectedValueOnce(new Error('offline'));
    render(<Editor page={page} />);
    fireEvent.click(await screen.findByRole('button', { name: 'Usar versão salva' }));
    expect(await screen.findByRole('alert')).toHaveTextContent('Seu rascunho foi mantido');
    expect(screen.getByRole('button', { name: 'Recuperar rascunho' })).toBeVisible();
    expect(textEditorDrafts.remove).not.toHaveBeenCalled();
  });

  it('nests a page card and adopts the parent revision before saving more writing', async () => {
    const alpha = { id: 'alpha', title: 'Alpha', sort_order: 0, parent_page_id: page.id };
    const beta = { id: 'beta', title: 'Beta', sort_order: 1000, parent_page_id: page.id };
    const card = (id: string, title: string) => ({ type: 'subPageBlock', attrs: { pageId: id, title, icon: '', source: 'child' } });
    const content = { type: 'doc' as const, content: [...doc('Before').content, card('alpha', 'Alpha'), card('beta', 'Beta'), ...doc('After').content] };
    const root = { ...page, content };
    let moved = false;
    vi.mocked(api.getSubPages).mockImplementation(async id => id === page.id ? (moved ? [beta] : [alpha,beta]) as Awaited<ReturnType<typeof api.getSubPages>> : []);
    vi.mocked(api.patchPage).mockImplementation(async () => { moved = true; return { ...alpha, revision: 2 } as Page; });
    vi.mocked(api.getPage).mockResolvedValue({ ...root, revision: 4, content: { type: 'doc', content: [...doc('Before').content,card('beta','Beta'),...doc('After').content] } });
    render(<Editor page={root} />, { wrapper: MemoryRouter });
    await waitFor(() => expect(captured.editor?.isEditable).toBe(true));
    const target = document.querySelector('[data-page-card="beta"]') as HTMLElement;
    vi.spyOn(target,'getBoundingClientRect').mockReturnValue({top:100,height:80,bottom:180} as DOMRect);
    const data=new Map<string,string>();const transfer={setData:(k:string,v:string)=>data.set(k,v),getData:(k:string)=>data.get(k)??'',get types(){return [...data.keys()];},effectAllowed:''} as unknown as DataTransfer;
    writePageDrag(transfer,{id:'alpha',title:'Alpha',origin:'editor',reference:false});
    const drop=new Event('drop',{bubbles:true,cancelable:true});Object.defineProperties(drop,{clientY:{value:140},dataTransfer:{value:transfer}});
    fireEvent(target,drop);
    await waitFor(() => expect(api.patchPage).toHaveBeenCalledWith('alpha',{parent_page_id:'beta',sort_order:0}));
    await waitFor(() => expect(document.querySelector('[data-page-card="alpha"]')).toBeNull());
    await waitFor(() => expect(captured.editor?.isEditable).toBe(true));
    expect(captured.editor?.getText()).toContain('Before');expect(captured.editor?.getText()).toContain('After');
    fireEvent.change(screen.getByRole('textbox',{name:'Título da página'}),{target:{value:'After move'}});
    fireEvent.click(screen.getByRole('button',{name:'Retry save'}));
    await waitFor(() => expect(api.savePage).toHaveBeenCalledWith(page.id,expect.objectContaining({revision:4,title:'After move'}),expect.anything()));
  });

});
